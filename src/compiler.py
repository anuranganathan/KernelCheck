"""Compile CUDA test programs with nvcc.

For each (test, configuration) pair this produces, in build/<config>/:
    <test_id>       the executable
    <test_id>.ptx   the PTX for the same source and flags

Commands are always built as argument lists and run without a shell, so no
string from the manifest is ever interpreted by a shell.
"""

import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path

from src.manifest import TestCase

# Compile statuses
SUCCESS = "SUCCESS"
COMPILE_ERROR = "COMPILE_ERROR"
TIMEOUT = "TIMEOUT"
SKIPPED_NO_CUDA = "SKIPPED_NO_CUDA"


@dataclass
class CompileResult:
    status: str
    executable: Path | None = None
    ptx_path: Path | None = None
    duration_s: float | None = None
    exit_code: int | None = None
    command: list[str] = field(default_factory=list)
    output: str = ""                 # compiler stdout + stderr (errors, warnings)
    ptx_error: str | None = None     # why PTX is missing, if it is


def build_command(nvcc: str, source: Path, output: Path, flags: list[str],
                  arch: str | None = None, ptx: bool = False) -> list[str]:
    command = [nvcc, *flags]
    if arch:
        command.append(f"-arch={arch}")
    command += ["-I", str(source.parent)]   # for kc_common.h
    if ptx:
        command.append("-ptx")
    command += ["-o", str(output), str(source)]
    return command


def _run_nvcc(command: list[str], timeout: float):
    """Run nvcc. Returns (process, None, "") on completion, or
    (None, TIMEOUT / COMPILE_ERROR, reason) if nvcc could not finish."""
    try:
        return subprocess.run(command, capture_output=True, text=True, timeout=timeout), None, ""
    except subprocess.TimeoutExpired:
        return None, TIMEOUT, f"nvcc did not finish within {timeout} s"
    except OSError as exc:
        return None, COMPILE_ERROR, f"could not start nvcc: {exc}"


def compile_test(test: TestCase, config_name: str, flags: list[str], nvcc: str | None,
                 build_dir: Path, timeout: float, arch: str | None = None) -> CompileResult:
    if nvcc is None:
        return CompileResult(SKIPPED_NO_CUDA, output="nvcc not found; compilation not attempted")

    out_dir = build_dir / config_name
    out_dir.mkdir(parents=True, exist_ok=True)
    executable = out_dir / test.id
    ptx_path = out_dir / f"{test.id}.ptx"
    # Remove results of an earlier run, so a failed compile can never leave
    # an old executable behind that would then be run and reported.
    executable.unlink(missing_ok=True)
    ptx_path.unlink(missing_ok=True)

    command = build_command(nvcc, test.source, executable, flags, arch)
    start = time.perf_counter()
    process, failure_status, failure = _run_nvcc(command, timeout)
    duration = time.perf_counter() - start

    if process is None:
        return CompileResult(failure_status, duration_s=duration, command=command, output=failure)

    output = (process.stdout + process.stderr).strip()
    if process.returncode != 0 or not executable.is_file():
        return CompileResult(COMPILE_ERROR, duration_s=duration, exit_code=process.returncode,
                             command=command, output=output)

    result = CompileResult(SUCCESS, executable=executable, duration_s=duration,
                           exit_code=process.returncode, command=command, output=output)

    # PTX is generated by a second, separate nvcc invocation with the same
    # flags. A PTX failure does not invalidate the executable; it only means
    # PTX analysis is skipped.
    ptx_process, _, ptx_failure = _run_nvcc(
        build_command(nvcc, test.source, ptx_path, flags, arch, ptx=True), timeout)
    if ptx_process is None:
        result.ptx_error = ptx_failure
    elif ptx_process.returncode != 0 or not ptx_path.is_file():
        result.ptx_error = (ptx_process.stdout + ptx_process.stderr).strip() or "PTX not produced"
    else:
        result.ptx_path = ptx_path
    return result
